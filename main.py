# Отправка вопроса
async def send_question(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    current_question = context.user_data['current_question']
    questions = context.user_data['questions']

    question_text = f"{context.user_data['name']}, {questions[current_question]}" if current_question == 0 else \
        questions[current_question]

    keyboard = [
        [InlineKeyboardButton("Да", callback_data='yes'), InlineKeyboardButton("Нет", callback_data='no')]
    ]
    reply_markup = InlineKeyboardMarkup(keyboard)

    if update.callback_query:
        await update.callback_query.message.reply_text(question_text, reply_markup=reply_markup)
    elif update.message:
        await update.message.reply_text(question_text, reply_markup=reply_markup)
    else:
        logger.error("Neither callback_query nor message is present in the update.")


