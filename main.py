# Создаем или подключаемся к базе данных
def init_db():
    logger.debug("Initializing database...")
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY,
            username TEXT,
            name TEXT
        )
    ''')
    conn.commit()
    logger.info("Database initialized successfully.")
    return conn


# Сохраняем пользователя в базу данных
def save_user(user_id, username, name):
    logger.debug(f"Saving user: {user_id}, {username}, {name}")
    conn = init_db()
    cursor = conn.cursor()
    cursor.execute('INSERT OR IGNORE INTO users (user_id, username, name) VALUES (?, ?, ?)', (user_id, username, name))
    conn.commit()
    conn.close()
    logger.info(f"User {user_id} saved to database.")
    write_usernames_to_txt()  # Обновляем текстовый файл после сохранения


# Запись юзернеймов в текстовый файл
def write_usernames_to_txt():
    logger.debug("Writing usernames to text file...")
    conn = init_db()
    cursor = conn.cursor()
    cursor.execute('SELECT username, name FROM users')
    users = cursor.fetchall()
    conn.close()

    with open(TXT_PATH, 'w', encoding='utf-8') as f:
        for user in users:
            f.write(f"{user[0]}, {user[1]}\n")
    logger.info("Usernames written to text file.")


