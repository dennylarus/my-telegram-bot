# Отправка рассылки
async def send_broadcast(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    logger.debug("Sending broadcast message.")
    message_text = context.user_data.get('message_text', '')
    media = context.user_data.get('media', None)

    conn = init_db()
    cursor = conn.cursor()
    cursor.execute('SELECT user_id, username FROM users')
    users = cursor.fetchall()
    conn.close()

    delivered_count = 0
    blocked_count = 0

    # Отправка сообщения каждому пользователю по одному
    for user in users:
        user_id, username = user
        try:
            if media:
                if 'photo' in media:  # Если это фото
                    await context.bot.send_photo(user_id, media['photo'], caption=message_text)
                elif 'video' in media:  # Если это видео
                    await context.bot.send_video(user_id, media['video'], caption=message_text)
                elif 'animation' in media:  # Если это гиф
                    await context.bot.send_animation(user_id, media['animation'], caption=message_text)
            else:
                await context.bot.send_message(user_id, message_text)

            delivered_count += 1
            logger.info(f"Message sent to user {user_id}.")
        except Exception as e:
            logger.error(f"Failed to send message to {user_id}: {e}")
            blocked_count += 1
            delete_user(user_id)

        await asyncio.sleep(2)  # Задержка между отправкой сообщений каждому пользователю в секундах

    await update.callback_query.message.reply_text(
        "<b>📢 Рассылка завершена!</b>\n"
        f"✅ Сообщение доставлено <b>{delivered_count}</b> пользователям,\n"
        f"✅ Сообщение доставлено <b>{delivered_count}</b> пользователям,\n"
        f"🚫 <b>{blocked_count}</b> пользователей заблокировали бота.",
        parse_mode='HTML'
    )
    logger.info(f"Broadcast completed. Delivered: {delivered_count}, Blocked: {blocked_count}.")

